import { useState } from 'ardo/react';
import { ArdoLink as Link, useArdoHref } from 'ardo/runtime';
import {
  FerraArticle,
  FerraCode,
  FerraCodePair,
  FerraDiagram,
  FerraSelect,
} from 'ferramenta-family/ferra';

import fixture from '../data/diagram-samples.json';

export function DiagramExample() {
  const [selected, setSelected] = useState('flowchart');
  const sample = fixture.samples.find(({ id }) => id === selected);
  if (!sample) throw new Error('Unknown diagram example.');
  const svgFile = useArdoHref(`/examples/${selected}.svg`);
  return (
    <FerraArticle
      id="example"
      title="A few lines become a diagram."
      introduction="Choose a flowchart, sequence or state diagram. Each preview is SVG generated by Ferrigura’s native CLI from the source beside it."
      meta={<Link to="/guide/getting-started/">Render the same source yourself</Link>}
    >
      <FerraSelect
        label="Diagram type"
        value={selected}
        options={fixture.samples.map(({ id, label }) => ({ value: id, label }))}
        onChange={(event) => {
          setSelected(event.target.value);
        }}
      />
      <FerraCodePair>
        <FerraCode caption="Mermaid source">{sample.source}</FerraCode>
        <FerraDiagram caption="Native SVG output" label={sample.description} svg={sample.svg} />
      </FerraCodePair>
      <p>
        <a href={svgFile}>Open the SVG at full size</a>
      </p>
      <p>
        The examples use the renderer’s light scheme and embedded font subsets. The website switches
        between build-time outputs; it runs no diagram renderer in your browser.
      </p>
    </FerraArticle>
  );
}
