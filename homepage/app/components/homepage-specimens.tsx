/** The same checks with the layout and the parse comparison, folded under the list. */
function CoverageTable() {
  return (
    <MonoTableView summary="Show every check as a table">
      {/* oxlint-disable-next-line jsx-a11y/no-noninteractive-tabindex -- A scrollable region needs focus. */}
      <div className="fgr-table" role="region" aria-label="Checks per diagram type" tabIndex={0}>
        <table className="mono-table">
          <thead>
            <tr>
              <th scope="col">Type</th>
              <th scope="col">Layout</th>
              <th scope="col" className="mono-num">
                Inputs read as Mermaid reads them
              </th>
              <th scope="col" className="mono-num">
                Drawings within 0.05 px
              </th>
              <th scope="col" className="mono-num">
                Not compared
              </th>
            </tr>
          </thead>
          <tbody>
            {coverage.types.map((row) => (
              <tr key={row.type}>
                <td>{row.type}</td>
                <td>{row.layout.replaceAll('`', '')}</td>
                <td className="mono-num">{grouped(row.parsed)}</td>
                <td className="mono-num">
                  {grouped(row.agreed)} of {grouped(row.compared)}
                </td>
                <td className="mono-num">{row.notCompared}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </MonoTableView>
  );
}

/** The geometry check per diagram type, from docs/diagrams/README.md. */
