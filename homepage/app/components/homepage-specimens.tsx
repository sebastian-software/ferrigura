/* Every drawing here is real output of the published npm package, written by
   scripts/render-diagram-samples.mjs into app/data/; nothing is drawn by hand. */

const credit = `Real output of Ferrigura (${renderingSource})`;

// The gallery's other drawings load when a visitor asks for them; the ones on
// the page from the start are imported above.
const drawings = import.meta.glob<string>(
  [
    '../data/diagrams/*.svg',
    '!../data/diagrams/flowchart.svg',
    '!../data/diagrams/mode-*.svg',
    '!../data/diagrams/scheme-*.svg',
  ],
  { query: '?raw', import: 'default' }
);
const fileUrls = import.meta.glob<string>('../data/diagrams/*.svg', {
  query: '?url',
  import: 'default',
  eager: true,
});
const urlOf = (file: string) => {
  const url = fileUrls[`../data/diagrams/${file}`];
  if (url === undefined) throw new Error(`No rendered file ${file}`);
  return url;
};

/** The gallery's first drawing, the one the page is prerendered with. */
function firstSample() {
  const [entry] = samples.samples;
  if (entry?.file !== 'flowchart.svg') throw new Error('The gallery starts with the flowchart');
  return entry;
}
const first = firstSample();

/** Build-time SVG from the published package, never visitor input. */
function Drawing({ svg, label, className }: { svg: string; label: string; className?: string }) {
  return (
    <div
      className={className === undefined ? 'fgr-drawing' : `fgr-drawing ${className}`}
      role="img"
      aria-label={label}
      // oxlint-disable-next-line react/no-danger -- Generated by scripts/render-diagram-samples.mjs.
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}

function Source({ children, label }: { children: string; label: string }) {
  return (
    // A long line scrolls inside the sheet; the keyboard can reach it.
    // oxlint-disable-next-line jsx-a11y/no-noninteractive-tabindex -- A scrollable region needs focus.
    <pre className="fgr-source" tabIndex={0} aria-label={label}>
      {children.replace(/\n$/, '')}
    </pre>
  );
}

/** The gallery: one diagram of six types, the text facing its drawing. */
export function DiagramGallery() {
  const [selected, setSelected] = useState(first.id);
  const [loaded, setLoaded] = useState<Record<string, string>>({ [first.file]: firstDrawing });
  const sample = samples.samples.find(({ id }) => id === selected) ?? first;
  const svg = loaded[sample.file] ?? firstDrawing;
  const choose = (id: string) => {
    const next = samples.samples.find((entry) => entry.id === id);
    if (next === undefined) return;
    if (loaded[next.file] !== undefined) {
      setSelected(id);
      return;
    }
    const load = drawings[`../data/diagrams/${next.file}`];
    if (load === undefined) throw new Error(`No rendered file ${next.file}`);
    void load().then((drawing) => {
      setLoaded((current) => ({ ...current, [next.file]: drawing }));
      setSelected(id);
    });
  };
  return (
    <figure className="mono-wide fgr-gallery">
      <MonoSegmented
        label="Diagram type"
        value={selected}
        options={samples.samples.map(({ id, label }) => ({ value: id, label }))}
        onChange={choose}
      />
      <MonoFacing>
        <MonoSheet label="As written" meta={`${sample.id}.mmd`}>
          <Source label={`${sample.label} diagram text`}>{sample.source}</Source>
        </MonoSheet>
        <MonoSheet label="As drawn by Ferrigura" meta={sample.file}>
          <Drawing svg={svg} label={sample.description} />
          <p className="fgr-open">
            <a href={urlOf(sample.file)}>Open the SVG file</a>
          </p>
        </MonoSheet>
      </MonoFacing>
      <MonoCaption>
        {credit}, rendered with <code>{"renderer.render(text, { colorScheme: 'light' })"}</code>.
        The page switches between files rendered ahead of time; no renderer runs in your browser.
      </MonoCaption>
    </figure>
  );
}

const kilobytes = (bytes: number) => `${(bytes / 1000).toFixed(1)} kB`;

/** What one file carries, counted in the gallery's flowchart, and one of its labels. */
export function FileContents() {
  const { file } = samples;
  return (
    <figure className="mono-wide fgr-file">
      <div className="fgr-single">
        <MonoSheet label="One label in the file, the decision node" meta={`${file.sample}.svg`}>
          <Source label="The markup of the Signed in? label">{file.label}</Source>
        </MonoSheet>
      </div>
      <MonoProofs
        className="fgr-proofs"
        items={[
          { label: 'The whole file', value: kilobytes(file.bytes) },
          {
            label: `Embedded font data, ${file.fontFaces === 1 ? 'one face' : `${file.fontFaces} faces`}`,
            value: kilobytes(file.fontBytes),
          },
          { label: 'Labels as SVG text', value: file.textElements },
          { label: 'HTML inside the drawing', value: file.htmlElements || 'none' },
          { label: 'Scripts', value: file.scripts || 'none' },
          { label: 'A second render', value: 'the same bytes' },
        ]}
      />
      <MonoCaption>
        {credit}: the flowchart from the top of the page. The markup is indented for reading; in the
        file it stands on one line.
      </MonoCaption>
    </figure>
  );
}

