import { MonoFacing, MonoSheet } from 'ferramenta-family/monografie';

import comparison from '../data/comparison.json';

/* Every drawing here is real output of the published packages, written by
   scripts/render-comparison.mjs into app/data/; nothing is drawn by hand.
   Ferrigura's file stands as an image, the way a site ships it: it carries
   its fonts. Mermaid's SVG stands in the page, the way Mermaid draws it, and
   takes the page's face (homepage-specimens.css). */

const ferrigura = comparison.renderedWith['@ferrigura/core'];
const mermaid = comparison.renderedWith.mermaid;

const markup = import.meta.glob<string>('../data/comparison/mermaid-*.svg', {
  query: '?raw',
  import: 'default',
  eager: true,
});
const fileUrls = import.meta.glob<string>('../data/comparison/*.svg', {
  query: '?url',
  import: 'default',
  eager: true,
});
const lookup = (files: Record<string, string>, file: string) => {
  const value = files[`../data/comparison/${file}`];
  if (value === undefined) throw new Error(`No rendered file ${file}`);
  return value;
};

/** The drawing's size from its viewBox, so the image keeps its proportions. */
function size(svg: string) {
  const box = /viewBox="([^"]+)"/.exec(svg)?.[1]?.split(/\s+/).map(Number);
  if (box?.length !== 4) throw new Error('A drawing has no viewBox');
  return { width: box[2] ?? 0, height: box[3] ?? 0 };
}

function example(id: string) {
  const entry = comparison.examples.find((candidate) => candidate.id === id);
  if (entry === undefined) throw new Error(`No side-by-side example ${id}`);
  return entry;
}

/** One example: the diagram text, then Ferrigura's drawing facing Mermaid's. */
export function SideBySide({ id }: { id: string }) {
  const entry = example(id);
  const mermaidSvg = lookup(markup, entry.mermaid);
  const { width, height } = size(mermaidSvg);
  return (
    <figure className="fgr-side">
      <figcaption>{entry.description}</figcaption>
      <MonoFacing>
        <MonoSheet label="Ferrigura" meta={ferrigura}>
          <img
            className="fgr-side-drawing"
            src={lookup(fileUrls, entry.ferrigura)}
            width={Math.round(width)}
            height={Math.round(height)}
            loading="lazy"
            alt={`Ferrigura's drawing: ${entry.description}`}
          />
        </MonoSheet>
        <MonoSheet label="Mermaid" meta={mermaid}>
          <div
            className="fgr-side-drawing"
            role="img"
            aria-label={`Mermaid's drawing: ${entry.description}`}
            // oxlint-disable-next-line react/no-danger -- Generated by scripts/render-comparison.mjs.
            dangerouslySetInnerHTML={{ __html: mermaidSvg }}
          />
        </MonoSheet>
      </MonoFacing>
      <p className="fgr-side-files">
        <a href={lookup(fileUrls, entry.ferrigura)}>Ferrigura’s SVG file</a>
        <a href={lookup(fileUrls, entry.mermaid)}>Mermaid’s SVG file</a>
      </p>
      <details className="fgr-side-source">
        <summary>Diagram text</summary>
        {/* oxlint-disable-next-line jsx-a11y/no-noninteractive-tabindex -- A scrollable region needs focus. */}
        <pre tabIndex={0} aria-label={`${entry.title}: diagram text`}>
          <code>{entry.source.replace(/\n$/, '')}</code>
        </pre>
      </details>
    </figure>
  );
}

/** The versions and the configuration both sides drew with, as recorded. */
export function Versions() {
  return (
    <>
      <code>@ferrigura/core</code> {ferrigura} and <code>mermaid</code> {mermaid}
    </>
  );
}

export function SharedConfig() {
  return (
    // oxlint-disable-next-line jsx-a11y/no-noninteractive-tabindex -- A scrollable region needs focus.
    <pre tabIndex={0} aria-label="The configuration both sides get">
      <code>{JSON.stringify(comparison.settings.config, null, 2)}</code>
    </pre>
  );
}
