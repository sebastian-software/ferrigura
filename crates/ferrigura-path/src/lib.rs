//! The bounding box of an SVG path as Chromium's `getBBox()` returns it, bit for bit.
//!
//! The route is Blink's, for an SVG path element of Chromium 151 (the Skia revision of its `DEPS`,
//! `0208108c7aed5f4e0faa525cbba52c238005a1ef`), and it is ported by reading those sources (`NOTICE.md`):
//!
//! 1. The path data is parsed into Blink's byte stream, with its numbers read in `float` by Blink's
//!    digit-by-digit parser (`number.rs`, `segments.rs`).
//! 2. The byte stream is built into the `SkPath` by `SVGPathBuilder` (`builder.rs`): relative points
//!    become absolute, the smooth curves are reflected, and an arc is `SkPathBuilder::arcTo`, which makes
//!    conics from float matrices (`skia.rs`).
//! 3. `getBBox()` is `SkPath::computeTightBounds()` of that path: the extremes of each curve in `float`
//!    (`bounds.rs`).
//!
//! The port is checked against Chromium's own boxes in `tests/corpus`, generated by
//! `tools/port/path-bounds.ts`.

#![forbid(unsafe_code)]

mod bounds;
mod builder;
mod number;
mod segments;
mod skia;

/// A box as `getBBox()` returns it: the four values are floats (`gfx::RectF`).
#[derive(Debug, Clone, Copy, Default, PartialEq)]
pub struct Rect {
    /// The left edge.
    pub x: f32,
    /// The top edge.
    pub y: f32,
    /// The width, `right - left`.
    pub width: f32,
    /// The height, `bottom - top`.
    pub height: f32,
}

/// The box of the path with the data `d`, as `getBBox()` of a path element with that `d` returns it. A
/// path with no segment has the empty box, which is all zeros.
#[must_use]
pub fn bounding_box(d: &str) -> Rect {
    let verbs = builder::build(&segments::parse(d));
    match bounds::tight_bounds(&verbs) {
        Some([x, y, width, height]) => Rect {
            x,
            y,
            width,
            height,
        },
        None => Rect::default(),
    }
}
