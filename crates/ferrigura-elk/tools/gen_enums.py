#!/usr/bin/env python3
"""Generate `src/core/data/enums.rs`: the ELK enums the port reads by name or ordinal.

Java enums are referenced by name in option values (`Enum.valueOf`, with an
index fallback in `LayoutOptionData.enumForString`) and ordered by ordinal in
`LayoutProcessorConfiguration`, so the constants keep their declaration order.
Only plain enums (constants, then an optional `;`) are read; enums with bodies
are reported and skipped.

Usage: gen_enums.py <path-to-elk-checkout> src/core/data/enums.rs
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_option_registry as registry  # noqa: E402

# Enums that have no option but are ordered or named by the layered algorithm.
EXTRA_ENUMS = ["IntermediateProcessorStrategy", "LayeredPhases", "GraphProperties", "LayerConstraint"]


def screaming(name):
    """CamelCase to SCREAMING_SNAKE_CASE, for constant names."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).upper()


# Packages whose declaration wins when several ELK packages reuse a simple name.
PREFERRED_PATHS = ["/alg/layered/", "/core/options/", "/core/", "/alg/common/"]


def preference(path):
    for rank, fragment in enumerate(PREFERRED_PATHS):
        if fragment in path:
            return rank
    return len(PREFERRED_PATHS)


def find_sources(elk_root):
    """Map each enum's simple name to its declaring source, preferring the ported packages."""
    found = {}
    for dirpath, _, files in os.walk(os.path.join(elk_root, "plugins")):
        if "/src/" not in dirpath + "/":
            continue
        for name in files:
            if not name.endswith(".java"):
                continue
            path = os.path.join(dirpath, name)
            with open(path, encoding="utf-8", errors="replace") as handle:
                body = registry.strip_comments_java(handle.read())
            for match in re.finditer(r"\benum\s+(\w+)\s*(?:implements[^{]*)?\{", body):
                name = match.group(1)
                rank = preference(path)
                if name not in found or rank < found[name][0]:
                    found[name] = (rank, path, body, match.end())
    return found


def constants(body, start):
    """Constant names of the enum whose `{` ends right before `start`."""
    depth = 1
    index = start
    text = []
    while index < len(body) and depth > 0:
        char = body[index]
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
        if depth > 0:
            text.append(char)
        index += 1
    section = "".join(text)
    # Constants end at the first top-level `;`; a body after it is not ours to read.
    level = 0
    end = len(section)
    for position, char in enumerate(section):
        if char in "({[":
            level += 1
        elif char in ")}]":
            level -= 1
        elif char == ";" and level == 0:
            end = position
            break
    head = section[:end]
    # A constant with its own class body (`A { ... }`) is not a plain constant.
    has_body = "{" in head
    names = []
    level = 0
    token = ""
    for char in head + ",":
        if char in "({[":
            level += 1
        elif char in ")}]":
            level -= 1
        if char == "," and level == 0:
            candidate = re.sub(r"@\w+(\([^)]*\))?", "", token).strip()
            if candidate:
                match = re.match(r"(\w+)", candidate)
                if not match:
                    raise SystemExit(f"cannot read constant in {candidate!r}")
                names.append(match.group(1))
            token = ""
        else:
            token += char
    return names, has_body


def main():
    elk_root, out_path = sys.argv[1], sys.argv[2]
    sources = find_sources(elk_root)
    wanted = set(EXTRA_ENUMS)
    for spec in registry.OPTIONS_SOURCE_ENUMS(elk_root):
        wanted.add(spec)
    lines = [
        "// @generated by crates/ferrigura-elk/tools/gen_enums.py from the ELK sources at",
        "// commit 9bc93474e (see docs-port/elk/SOURCES.md). Do not edit by hand.",
        "",
        "#![allow(clippy::upper_case_acronyms, non_camel_case_types)]",
        "",
        "use super::JavaEnum;",
        "",
    ]
    skipped = []
    registered = []
    for name in sorted(wanted):
        if name not in sources:
            skipped.append((name, "not found"))
            continue
        _, _, body, start = sources[name]
        names, has_body = constants(body, start)
        if has_body:
            skipped.append((name, "has a body"))
            continue
        lines.append("/// The ELK enum `%s`, constants in declaration order (their ordinals)." % name)
        lines.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]")
        lines.append("pub enum %s {" % name)
        for constant in names:
            lines.append("    %s," % constant)
        lines.append("}")
        lines.append("")
        lines.append("impl JavaEnum for %s {" % name)
        lines.append("    /// `Enum.valueOf`, falling back to an ordinal index as `enumForString` does.")
        lines.append("    fn from_java_text(text: &str) -> Option<Self> {")
        lines.append("        match text {")
        for constant in names:
            lines.append("            \"%s\" => Some(%s::%s)," % (constant, name, constant))
        lines.append("            _ => text.parse::<usize>().ok().and_then(|index| ALL_%s.get(index).copied())," % screaming(name))
        lines.append("        }")
        lines.append("    }")
        lines.append("")
        lines.append("    fn java_name(self) -> &'static str {")
        lines.append("        match self {")
        for constant in names:
            lines.append("            %s::%s => \"%s\"," % (name, constant, constant))
        lines.append("        }")
        lines.append("    }")
        lines.append("}")
        lines.append("")
        lines.append("/// Every constant of `%s`, in ordinal order." % name)
        lines.append("const ALL_%s: &[%s] = &[%s];" % (screaming(name), name, ", ".join("%s::%s" % (name, c) for c in names)))
        lines.append("")
        registered.append(name)
    lines.append("/// The canonical constant name for `text` in the enum class `class`, if it is one.")
    lines.append("///")
    lines.append("/// `Some(None)` means `text` is not a constant of that class, so Java would give `null`.")
    lines.append("/// `None` means the class is not one this port has generated.")
    lines.append("pub fn canonical_constant(class: &str, text: &str) -> Option<Option<&'static str>> {")
    lines.append("    Some(match class {")
    for name in registered:
        lines.append("        \"%s\" => %s::from_java_text(text).map(JavaEnum::java_name)," % (name, name))
    lines.append("        _ => return None,")
    lines.append("    })")
    lines.append("}")
    lines.append("")
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    for name, reason in skipped:
        print(f"skipped {name}: {reason}")
    print(f"wrote {len(wanted) - len(skipped)} enums to {out_path}")


if __name__ == "__main__":
    main()
