// Prints one data file for crates/ferrigura-swimlane/tests/data, as V8 computes it.
//
//   node crates/ferrigura-swimlane/tools/js-semantics.mjs <to-fixed|js-round|ascii-sorted-len2|ascii-pairs|ascii-sorted-len3>
//
// Redirect the output to tests/data/<name>.txt (ascii-sorted-len3 is for a one-off check and is not committed).
// The random draws use mulberry32 with a fixed seed, so the output is the same on every run of the same node.
// Recorded with Node v24.21.0 (V8 13.6, ICU 78.3, default locale en-US).
//
// File format: lines starting with '#' are comments. to-fixed and js-round are tab-free, space-separated
// fields. The ascii files hold JSON string literals (JSON.stringify): a string with a space, a quote or a
// backslash is escaped by JSON, and every other printable ASCII character is written as it is.
// Empty strings are "".

const SEED = 0x5eed2026;
const ALPHABET = Array.from({ length: 95 }, (_, i) => String.fromCharCode(0x20 + i));

function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const view = new DataView(new ArrayBuffer(8));
function bitsOf(x) {
  view.setFloat64(0, x);
  return view.getBigUint64(0).toString(16).padStart(16, "0");
}
function fromBits(hex) {
  view.setBigUint64(0, BigInt("0x" + hex));
  return view.getFloat64(0);
}

function toFixedData() {
  const rand = mulberry32(SEED);
  const int = (n) => Math.floor(rand() * n);
  const sign = () => (rand() < 0.5 ? -1 : 1);
  const cases = [];
  const named = [
    [0.25, 1], [0.35, 1], [2.5, 0], [-2.5, 0], [1.005, 2], [1e-7, 6], [-0.04, 1], [-0, 1],
    [NaN, 2], [1e20, 0], [1e21, 2], [-1e21, 2], [1.2345e25, 3], [0.125, 2], [-1e-300, 2],
    [9.96, 1], [99.5, 0], [0.5, 0], [1.5, 0], [Infinity, 2], [-Infinity, 2], [5e-324, 100],
    [0.1, 100], [1e-7, 100], [123.456, 100], [5e-324, 0], [1.45, 1], [8.345, 2],
    [1.0000000000000002, 15], [-0.5, 0], [-0.0001, 2], [1e21, 100], [999999999999999999999, 0],
  ];
  for (const [x, d] of named) cases.push([x, d]);
  // Exact binary fractions k / 2^j: decimal ties at many digit counts.
  for (let i = 0; i < 700; i++) {
    const j = int(13);
    cases.push([sign() * (int(1 << 20) / 2 ** j), int(13)]);
  }
  // Random doubles over a wide binary range, below 1e21.
  for (let i = 0; i < 600; i++) {
    const e = -40 + int(81);
    cases.push([sign() * (1 + rand()) * 2 ** e, int(21)]);
  }
  // Decimal literals n / 10^e: not exact in binary, so the ties are near ties.
  for (let i = 0; i < 300; i++) {
    const e = int(8);
    cases.push([sign() * (int(10 ** (1 + int(8))) / 10 ** e), int(9)]);
  }
  // Large values below 1e21 and tiny subnormal values, with long digit counts.
  for (let i = 0; i < 200; i++) {
    cases.push([sign() * (1 + rand()) * 10 ** (15 + int(5)), int(4)]);
  }
  for (let i = 0; i < 100; i++) {
    cases.push([sign() * (1 + rand()) * 2 ** -(1 + int(1074)), int(101)]);
  }
  // At and above 1e21: ToString of the magnitude, with the sign.
  for (let i = 0; i < 100; i++) {
    cases.push([sign() * (1 + rand()) * 10 ** (21 + int(287)), int(101)]);
  }
  const lines = [
    "# Number.prototype.toFixed(digits): <bits of x as 16 hex digits> <digits> <expected>.",
    "# Generated by: node crates/ferrigura-swimlane/tools/js-semantics.mjs to-fixed (Node v24.21.0).",
  ];
  for (const [x, d] of cases) {
    const expected = x.toFixed(d);
    lines.push(`${bitsOf(x)} ${d} ${expected}`);
  }
  return lines;
}

function jsRoundData() {
  const rand = mulberry32(SEED ^ 0x7f);
  const int = (n) => Math.floor(rand() * n);
  const sign = () => (rand() < 0.5 ? -1 : 1);
  const xs = [
    -0, 0, 0.5, -0.5, 1.5, -1.5, 2 ** 52 + 1, 0.49999999999999994, -0.49999999999999994,
    2.5, -2.5, -0.4, -1e-320, NaN, Infinity, -Infinity, 4503599627370495.5,
    -4503599627370495.5, 2 ** 52, -(2 ** 52), 1e308, -1e308, 1e-320, -0.5000000000000001,
    0.5000000000000001, 2 ** -53, -(2 ** -53), 1.4999999999999998, 3.5, -3.5,
  ];
  // Uniform 64-bit patterns: every class of double, including NaN payloads and subnormals.
  for (let i = 0; i < 500; i++) {
    const hi = int(2 ** 32);
    const lo = int(2 ** 32);
    xs.push(fromBits((((BigInt(hi) << 32n) | BigInt(lo))).toString(16).padStart(16, "0")));
  }
  // Half-integers nudged by a few ulps, on both sides of the tie.
  for (let i = 0; i < 500; i++) {
    const magnitude = int(2 ** 21) + 0.5;
    const nudge = int(9) - 4;
    const bits = BigInt("0x" + bitsOf(magnitude)) + BigInt(nudge);
    xs.push(sign() * fromBits(bits.toString(16).padStart(16, "0")));
  }
  // Exact binary values with a fraction of one half, at a range of exponents.
  for (let i = 0; i < 500; i++) {
    xs.push(sign() * (int(2 ** 30) + 0.5) * 2 ** (-20 + int(61)));
  }
  // Decimal literals of three digits after the point.
  for (let i = 0; i < 500; i++) {
    xs.push((int(2e10) - 1e10) / 1000);
  }
  const lines = [
    "# Math.round(x): <bits of x as 16 hex digits> <bits of Math.round(x) as 16 hex digits>.",
    "# NaN is written with the bits V8 returns; the test compares NaN as NaN.",
    "# Generated by: node crates/ferrigura-swimlane/tools/js-semantics.mjs js-round (Node v24.21.0).",
  ];
  for (const x of xs) lines.push(`${bitsOf(x)} ${bitsOf(Math.round(x))}`);
  return lines;
}

// Every string of exactly `length` printable ASCII characters, in lexicographic order of the alphabet.
function stringsOfLength(length) {
  let level = [""];
  for (let len = 1; len <= length; len++) {
    const next = [];
    for (const prefix of level) for (const c of ALPHABET) next.push(prefix + c);
    level = next;
  }
  return level;
}

// The empty string and every string of length 1 or 2.
function stringsUpTo2() {
  return ["", ...stringsOfLength(1), ...stringsOfLength(2)];
}

function sortedData(strings, name) {
  const sorted = [...strings].sort((a, b) => a.localeCompare(b));
  for (let i = 1; i < sorted.length; i++) {
    if (sorted[i - 1].localeCompare(sorted[i]) >= 0) {
      throw new Error(`not a strict order at ${i}: ${JSON.stringify(sorted[i - 1])}`);
    }
  }
  const lines = [
    `# ${strings.length} strings of printable ASCII (0x20 to 0x7E), sorted by a.localeCompare(b) (ascending).`,
    `# Generated by: node crates/ferrigura-swimlane/tools/js-semantics.mjs ${name} (Node v24.21.0, ICU 78.3).`,
  ];
  for (const s of sorted) lines.push(JSON.stringify(s));
  return lines;
}

function pairsData() {
  const rand = mulberry32(SEED ^ 0xa5);
  const int = (n) => Math.floor(rand() * n);
  const randomString = (alphabet, maxLength) => {
    const length = 1 + int(maxLength);
    let s = "";
    for (let i = 0; i < length; i++) s += alphabet[int(alphabet.length)];
    return s;
  };
  const lines = [
    "# a.localeCompare(b) for 200000 pairs of printable ASCII strings of length 1 to 6, as",
    "# <JSON a><TAB><JSON b><TAB><sign>, the sign being -1, 0 or 1 as V8 gives it.",
    "# Pairs 0 to 99999: independent strings over all of printable ASCII.",
    "# Pairs 100000 to 199999: b is a close variant of a (letter case flipped, a character replaced or",
    "# added or removed), over a small alphabet, so that the primary and tertiary levels both decide.",
    "# Generated by: node crates/ferrigura-swimlane/tools/js-semantics.mjs ascii-pairs (Node v24.21.0, ICU 78.3).",
  ];
  const small = "aAbBcCxX_-. 19";
  for (let i = 0; i < 200000; i++) {
    let a;
    let b;
    if (i < 100000) {
      a = randomString(ALPHABET.join(""), 6);
      b = randomString(ALPHABET.join(""), 6);
    } else {
      a = randomString(small, 6);
      b = [...a]
        .map((c) => {
          if (rand() < 1 / 3 && c.toLowerCase() !== c.toUpperCase()) {
            return c === c.toLowerCase() ? c.toUpperCase() : c.toLowerCase();
          }
          if (rand() < 1 / 4) return small[int(small.length)];
          return c;
        })
        .join("");
      if (rand() < 1 / 4 && b.length < 6) b += small[int(small.length)];
      else if (rand() < 1 / 4 && b.length > 1) b = b.slice(0, -1);
      if (rand() < 1 / 8) b = a;
    }
    const sign = Math.sign(a.localeCompare(b));
    lines.push(`${JSON.stringify(a)}\t${JSON.stringify(b)}\t${sign}`);
  }
  return lines;
}

const command = process.argv[2];
const commands = {
  "to-fixed": toFixedData,
  "js-round": jsRoundData,
  "ascii-sorted-len2": () => sortedData(stringsUpTo2(), "ascii-sorted-len2"),
  "ascii-pairs": pairsData,
  "ascii-sorted-len3": () => sortedData(stringsOfLength(3), "ascii-sorted-len3"),
};
if (!commands[command]) {
  console.error(`usage: node crates/ferrigura-swimlane/tools/js-semantics.mjs <${Object.keys(commands).join("|")}>`);
  process.exit(2);
}
process.stdout.write(commands[command]().join("\n") + "\n");
