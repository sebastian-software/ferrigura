    /// An object with one option set to a number that `json!` cannot write (infinity or NaN).
    fn with_number(section: &str, option: &str, number: f64) -> Value {
        let inner = Value::Object(
            [(option.to_owned(), Value::Number(number))]
                .into_iter()
                .collect(),
        );
        Value::Object([(section.to_owned(), inner)].into_iter().collect())
    }

