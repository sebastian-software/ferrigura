//! The lenient reading of the configuration's types.
//!
//! The reference never checks the types of its configuration. A value is kept as the user wrote it,
//! and each use site reads it as JavaScript does: `rankSpacing: '100'` draws with 100. The typed
//! view is what the renderers read, so every option needs a value of its type. [`read_types`]
//! makes it so, and reports each value it changes. The rule, for a value of the wrong type:
//!
//! - A string that JavaScript's `Number()` reads as a finite number is read as that number, where
//!   the schema asks for a number or an integer. An integer must be whole, so `'100.5'` is not one.
//! - Any other value of the wrong type is replaced by the option's default, the value that
//!   [`defaults`](super::defaults) gives it. An option without a default is left unset.
//! - An item of an array that has the wrong type is dropped.
//!
//! A value that is kept is not reported. Each read value is reported with its number, and each
//! replacement and dropped item with what was used instead. The effective configuration, which the
//! differential run compares, is not changed by any of this.

use crate::value::Value;

/// The bound below which a [`Value`] offers a number as an integer to a deserializer. It is the
/// same bound as in `value.rs`: a whole number at or above it is an `f64` there, and an `i64` field
/// would refuse it.
const WHOLE_NUMBER_LIMIT: f64 = 9.0e15;

/// The type of one option, as the schema gives it. Generated by `build.rs` into `FIELD_TYPES`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FieldType {
    /// An object: a section, or an object without named options.
    Object,
    /// A value of one of the listed types. More than one when the schema names a union.
    Scalars(&'static [Scalar]),
    /// An array whose items have one of the listed types. An empty list leaves the items unchecked.
    Array(&'static [Scalar]),
}

/// A scalar type of the schema.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Scalar {
    /// A string.
    String,
    /// A number, which may be `NaN` or infinite.
    Number,
    /// A whole number.
    Integer,
    /// A boolean.
    Boolean,
}

impl Scalar {
    /// The name the schema gives the type.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::String => "string",
            Self::Number => "number",
            Self::Integer => "integer",
            Self::Boolean => "boolean",
        }
    }

    /// Whether the value already has this type. An integer is a whole number below the bound.
    fn accepts(self, value: &Value) -> bool {
        match (self, value) {
            (Self::String, Value::String(_))
            | (Self::Number, Value::Number(_))
            | (Self::Boolean, Value::Bool(_)) => true,
            (Self::Integer, Value::Number(number)) => is_integer(*number),
            _ => false,
        }
    }
}

impl FieldType {
    /// The type as the warnings name it: `object`, `string or number`, `array of string`.
    #[must_use]
    pub fn expected(self) -> String {
        match self {
            Self::Object => "object".to_owned(),
            Self::Scalars(scalars) => scalar_names(scalars),
            Self::Array([]) => "array".to_owned(),
            Self::Array(items) => format!("array of {}", scalar_names(items)),
        }
    }
}

/// A value of the configuration that does not have the type its option needs, and what was done
/// with it. [`typed_with_warnings`](super::typed_with_warnings) returns them.
#[derive(Debug, Clone, PartialEq)]
pub struct ConfigWarning {
    /// The option, by its keys from the top of the configuration: `flowchart.rankSpacing`. An item
    /// of an array is written as its index in brackets after the array's path.
    pub path: String,
    /// The type the option needs, as `FieldType::expected` names it.
    pub expected: String,
    /// The value that was found.
    pub found: Value,
    /// What the reading did with the value.
    pub outcome: Outcome,
}

/// What the reading did with a value of the wrong type.
#[derive(Debug, Clone, PartialEq)]
pub enum Outcome {
    /// A string that JavaScript reads as this number; the number is used.
    Read(f64),
    /// The option takes its default instead, which is `None` when the option has none and is left
    /// unset.
    Replaced(Option<Value>),
    /// An array item that is dropped.
    Dropped,
}

/// The options of a schema, as a tree that [`read_types`] walks. It is built once from the flat list
/// of the schema's option paths (`FIELD_TYPES`), so that reading a configuration looks up each
/// option once, in its parent, and allocates nothing for a value that has its type.
pub(super) struct Schema {
    nodes: Vec<Node>,
}

/// A key of the schema: an option with a type, or a key that is only the parent of options with types.
struct Node {
    /// The key of the option in its parent.
    key: &'static str,
    /// The path of the option from the top of the configuration. It names the option in the warnings
    /// and finds its default.
    path: &'static [&'static str],
    /// The place of the option in the list, which orders the warnings as the list does. Unused by a
    /// key that has no type of its own.
    position: usize,
    /// The type of the option; `None` for a key that is only the parent of options with types.
    field_type: Option<FieldType>,
    children: Vec<Node>,
}

impl Schema {
    /// The schema of a list of option paths, parents first, as `FIELD_TYPES` gives them.
    #[must_use]
    pub(super) fn new(field_types: &'static [(&'static [&'static str], FieldType)]) -> Self {
        let mut nodes = Vec::new();
        for (position, (path, field_type)) in field_types.iter().enumerate() {
            if !path.is_empty() {
                insert(&mut nodes, path, 0, position, *field_type);
            }
        }
        Self { nodes }
    }
}

/// Puts the option at `path` into the tree, below its parents at `depth` and deeper, and creates the
/// keys on the way that are not there yet.
fn insert(
    nodes: &mut Vec<Node>,
    path: &'static [&'static str],
    depth: usize,
    position: usize,
    field_type: FieldType,
) {
    let key = path[depth];
    let index = match nodes.iter().position(|node| node.key == key) {
        Some(index) => index,
        None => {
            nodes.push(Node {
                key,
                path: &path[..=depth],
                position: usize::MAX,
                field_type: None,
                children: Vec::new(),
            });
            nodes.len() - 1
        }
    };
    let node = &mut nodes[index];
    if depth + 1 == path.len() {
        node.position = position;
        node.field_type = Some(field_type);
    } else {
        insert(&mut node.children, path, depth + 1, position, field_type);
    }
}

/// Makes every option of `value` have the type the schema gives it, parents before children, and
/// returns each change in the order of the schema's list. `defaults` is the configuration's defaults,
/// which replace a value that cannot be read. An option below an absent parent is not visited. A
/// parent of the wrong type is replaced when it is visited, before its options, so the options are
/// read from the defaults.
pub(super) fn read_types(
    value: &mut Value,
    defaults: &Value,
    schema: &Schema,
) -> Vec<ConfigWarning> {
    let mut found = Vec::new();
    visit(value, &schema.nodes, defaults, &mut found);
    // A stable sort by position: each option's changes are in the order they were made, and the
    // options are in the order of the list.
    found.sort_by_key(|(position, _)| *position);
    found.into_iter().map(|(_, warning)| warning).collect()
}

/// Reads the options below `parent` that `nodes` describe, each with its children.
fn visit(
    parent: &mut Value,
    nodes: &[Node],
    defaults: &Value,
    found: &mut Vec<(usize, ConfigWarning)>,
) {
    for node in nodes {
        let Some(slot) = parent.get_mut(node.key) else {
            continue;
        };
        if let Some(field_type) = node.field_type
            && read_value(slot, field_type, node, found)
        {
            let default = default_at(defaults, node.path).cloned();
            found.push((
                node.position,
                ConfigWarning {
                    path: node.path.join("."),
                    expected: field_type.expected(),
                    found: slot.clone(),
                    outcome: Outcome::Replaced(default.clone()),
                },
            ));
            match default {
                Some(default) => *slot = default,
                None => {
                    if let Some(map) = parent.as_object_mut() {
                        map.remove(node.key);
                    }
                    continue;
                }
            }
        }
        visit(slot, &node.children, defaults, found);
    }
}

/// Reads one value against its type, in place. Returns whether the value must be replaced by the
/// option's default; a read or a dropped item is reported here, a replacement by the caller.
fn read_value(
    slot: &mut Value,
    field_type: FieldType,
    node: &Node,
    found: &mut Vec<(usize, ConfigWarning)>,
) -> bool {
    match field_type {
        FieldType::Object => !slot.is_object(),
        FieldType::Scalars(scalars) => match read_scalars(slot, scalars) {
            Reading::Kept => false,
            Reading::Read(number) => {
                found.push((
                    node.position,
                    ConfigWarning {
                        path: node.path.join("."),
                        expected: field_type.expected(),
                        found: slot.clone(),
                        outcome: Outcome::Read(number),
                    },
                ));
                *slot = Value::Number(number);
                false
            }
            Reading::Refused => true,
        },
        FieldType::Array(items) => match slot {
            Value::Array(list) => {
                if !items.is_empty() {
                    read_items(list, items, node, found);
                }
                false
            }
            _ => true,
        },
    }
}

/// Reads the items of an array option in place: a read item is replaced by its number, and an item
/// of the wrong type is dropped. The items keep their order.
fn read_items(
    list: &mut Vec<Value>,
    items: &[Scalar],
    node: &Node,
    found: &mut Vec<(usize, ConfigWarning)>,
) {
    let mut index = 0;
    list.retain_mut(|item| {
        let position = index;
        index += 1;
        match read_scalars(item, items) {
            Reading::Kept => true,
            Reading::Read(number) => {
                found.push((
                    node.position,
                    ConfigWarning {
                        path: item_path(node, position),
                        expected: scalar_names(items),
                        found: item.clone(),
                        outcome: Outcome::Read(number),
                    },
                ));
                *item = Value::Number(number);
                true
            }
            Reading::Refused => {
                found.push((
                    node.position,
                    ConfigWarning {
                        path: item_path(node, position),
                        expected: scalar_names(items),
                        found: item.clone(),
                        outcome: Outcome::Dropped,
                    },
                ));
                false
            }
        }
    });
}

/// The path of an item of an array option, as the warnings name it: `option[index]`.
fn item_path(node: &Node, index: usize) -> String {
    format!("{}[{index}]", node.path.join("."))
}

/// What reading a value against a set of scalar types gives.
enum Reading {
    /// The value has one of the types, and stays.
    Kept,
    /// A string that reads as this number, for a number or an integer that the string satisfies.
    Read(f64),
    /// Neither: the value is wrong.
    Refused,
}

fn read_scalars(value: &Value, scalars: &[Scalar]) -> Reading {
    if scalars.iter().any(|scalar| scalar.accepts(value)) {
        return Reading::Kept;
    }
    let Value::String(text) = value else {
        return Reading::Refused;
    };
    let Some(number) = js_number(text) else {
        return Reading::Refused;
    };
    scalars
        .iter()
        .find_map(|scalar| match scalar {
            Scalar::Number => Some(Reading::Read(number)),
            Scalar::Integer if is_integer(number) => Some(Reading::Read(number)),
            _ => None,
        })
        .unwrap_or(Reading::Refused)
}

/// Whether a number is a whole number that a deserializer reads as an integer.
fn is_integer(number: f64) -> bool {
    number.is_finite() && number.fract() == 0.0 && number.abs() < WHOLE_NUMBER_LIMIT
}

fn scalar_names(scalars: &[Scalar]) -> String {
    scalars
        .iter()
        .map(|scalar| scalar.name())
        .collect::<Vec<_>>()
        .join(" or ")
}

/// The default of the option at `path`, from the configuration's defaults.
fn default_at<'a>(defaults: &'a Value, path: &[&str]) -> Option<&'a Value> {
    path.iter()
        .try_fold(defaults, |node, segment| node.get(segment))
}

/// `Number(text)` as JavaScript computes it, when the result is finite; `None` when it is `NaN` or
/// an infinity. Surrounding white space is ignored, the empty string is zero, and the `0x`, `0o`
/// and `0b` forms take no sign. Decimal numbers are rounded as the parser of the platform rounds
/// them, which is correct rounding, as JavaScript requires; the radix forms are rounded to nearest,
/// ties to even.
#[must_use]
pub fn js_number(text: &str) -> Option<f64> {
    let text = text.trim_matches(is_js_white_space);
    if text.is_empty() {
        return Some(0.0);
    }
    let bits_per_digit = match text.get(..2) {
        Some("0x" | "0X") => Some(4),
        Some("0o" | "0O") => Some(3),
        Some("0b" | "0B") => Some(1),
        _ => None,
    };
    match bits_per_digit {
        Some(bits) => radix_number(&text[2..], bits),
        None => decimal_number(text),
    }
}

/// The white space and line terminators of ECMAScript's `StrWhiteSpaceChar`.
fn is_js_white_space(c: char) -> bool {
    matches!(
        c,
        '\t' | '\n'
            | '\u{B}'
            | '\u{C}'
            | '\r'
            | ' '
            | '\u{A0}'
            | '\u{1680}'
            | '\u{2028}'
            | '\u{2029}'
            | '\u{202F}'
            | '\u{205F}'
            | '\u{3000}'
            | '\u{FEFF}'
    ) || ('\u{2000}'..='\u{200A}').contains(&c)
}

/// A decimal literal with an optional sign: digits with an optional point, and an optional exponent.
fn decimal_number(text: &str) -> Option<f64> {
    let (negative, unsigned) = match text.strip_prefix('-') {
        Some(rest) => (true, rest),
        None => (false, text.strip_prefix('+').unwrap_or(text)),
    };
    let (mantissa, exponent) = match unsigned.find(['e', 'E']) {
        Some(at) => (&unsigned[..at], Some(&unsigned[at + 1..])),
        None => (unsigned, None),
    };
    let (whole, fraction) = mantissa.split_once('.').unwrap_or((mantissa, ""));
    if !all_digits(whole) || !all_digits(fraction) || (whole.is_empty() && fraction.is_empty()) {
        return None;
    }
    let exponent = match exponent {
        None => "0",
        Some(exponent) => {
            let digits = exponent.strip_prefix(['+', '-']).unwrap_or(exponent);
            if !all_digits(digits) || digits.is_empty() {
                return None;
            }
            exponent
        }
    };
    let whole = if whole.is_empty() { "0" } else { whole };
    let fraction = if fraction.is_empty() { "0" } else { fraction };
    let sign = if negative { "-" } else { "" };
    format!("{sign}{whole}.{fraction}e{exponent}")
        .parse::<f64>()
        .ok()
        .filter(|number| number.is_finite())
}

/// A literal in base 2, 8 or 16, with `bits_per_digit` bits a digit: its exact value, rounded to
/// nearest with ties to even, or `None` when it is not finite.
fn radix_number(digits: &str, bits_per_digit: u32) -> Option<f64> {
    if digits.is_empty() {
        return None;
    }
    let mut bits = Vec::new();
    for c in digits.chars() {
        let value = c.to_digit(1 << bits_per_digit)?;
        for shift in (0..bits_per_digit).rev() {
            bits.push((value >> shift) & 1 == 1);
        }
    }
    let Some(first) = bits.iter().position(|bit| *bit) else {
        return Some(0.0);
    };
    let significant = &bits[first..];

    // The top 53 bits make the mantissa; the bit below them decides the rounding, with the bits
    // after it as the sticky bit. A longer literal has its value scaled by a power of two.
    let length = significant.len();
    let kept = length.min(53);
    let mut mantissa = significant[..kept]
        .iter()
        .fold(0_u64, |acc, bit| (acc << 1) | u64::from(*bit));
    let mut exponent = length - kept;
    if length > 53 {
        let round = significant[53];
        let sticky = significant[54..].iter().any(|bit| *bit);
        if round && (sticky || mantissa & 1 == 1) {
            mantissa += 1;
            if mantissa == 1 << 53 {
                mantissa >>= 1;
                exponent += 1;
            }
        }
    }
    // A mantissa of 53 bits times 2^971 is the largest finite double; one more power overflows.
    if exponent > 971 {
        return None;
    }
    let scale = 2_f64.powi(i32::try_from(exponent).ok()?);
    Some(mantissa as f64 * scale)
}

fn all_digits(text: &str) -> bool {
    text.bytes().all(|byte| byte.is_ascii_digit())
}

